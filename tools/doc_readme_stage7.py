"""The parts of README and README_PROVENANCE that describe the spreadsheet 7plus1_status_2026-10-28.xlsx (the state of the repository at commit
102f399, 28 October 2026) and its three documents.  Every number is read from tools/status_2026-10-28.json or recomputed by
doc_status_common; every equation used is written in the document that uses it."""
import doc_status_common as C


def present():
    return C.present()


def abstract_text():
    return ', section 11 the spreadsheet of 28 October 2026 on the state of the repository'


def file_rows():
    return [
        ['`%s.xlsx`' % C.NAME, 'a spreadsheet of the state of the repository at commit 102f399 (28 October 2026): the four commits of that day up to it, the 30 '
         'documents with their pages and loose lines, the rewritten paragraphs, the results of the twelve check programs and of the checks of the '
         'notebook, the comparison of a fresh clone with the commit, and the private files kept out of the repository; every total is a formula'],
        ['`%s*` (`.md`, `.tex`, `.pdf`)' % C.NAME, 'the same tables and formulas as a document, with its symbol dictionary and its provenance record'],
        ['`tools/status_2026-10-28.json`, `tools/make_status_xlsx.py`', 'the data of the spreadsheet and the program that writes it (openpyxl; '
         'LibreOffice, if installed, computes and stores the values of its formulas)'],
    ]


def process_item():
    return ('The spreadsheet of 28 October 2026: its numbers were gathered from the history of the repository (`git log`, `git show`), the '
            'PDFs and the logs of LaTeX of three builds, the outputs of the twelve check programs and the record of the evaluation of 7+1.nb, '
            'into `tools/status_2026-10-28.json`; `tools/make_status_xlsx.py` writes the spreadsheet from it with openpyxl, and LibreOffice '
            '(headless) computes and stores the values of its formulas. The document, its symbol dictionary and its provenance record are '
            'generated by `tools/doc_status.py`, `tools/doc_status_symbols.py` and `tools/doc_status_provenance.py` from the data that '
            '`tools/doc_status_common.py` gathers; this record and the README describe them with `tools/doc_readme_stage7.py`.')


def provenance_section(d, D, runs, secno=11):
    S = C.load()
    dc = S['described_commit']
    cmp_ = C.stored_comparison(S)
    cc = C.commit_checks(S); pc = C.page_checks(S); fp = C.formula_presence(dc); prc = C.program_checks(S, runs)
    d.h1('%d. The spreadsheet of 28 October 2026' % secno)
    d.p('This section records the provenance of the spreadsheet `%s.xlsx` and of its three documents, which were added to the repository '
        'after commit %s.' % (C.NAME, dc))
    d.h2('%d.1 The task' % secno)
    d.ol(['Create a spreadsheet from the report on the clean-up of the loose lines of 28 October 2026 (summarized; the original wording is the '
          'author’s private working material).',
          'Add the spreadsheet to the repository and push it.'])
    d.h2('%d.2 Sources and decisions' % secno)
    d.p('The spreadsheet records the state of the repository at commit %s: %d commits, %d documents with %d pages, %d rewritten paragraphs, '
        'the results of %d check programs, the checks of the notebook, a fresh clone rebuilt from scratch, and %d private files. Its numbers come '
        'from `git log` and `git show` (the commits and the changed documents), `pdfinfo` (the pages), the logs of LaTeX of three builds (the '
        'loose lines), the outputs of the check programs, `tools/eval_log_7p1.txt` and the evaluated notebook. Decisions: the numbers are kept '
        'in a data file and the spreadsheet is written from it by a program; every total and every summary value is a formula, and LibreOffice '
        'stores the computed values; the private files are described without their names; the version in the repository is written for its '
        'readers and differs from the first version delivered to the author in wording and layout only.'
        % (dc, len(S['commits']), len(S['documents']), sum(x['pages'] for x in S['documents']),
           sum(1 for f in S['fixes'] if f['how'] in ('Display', 'Code block', 'Reworded')), len(S['programs']), len(S['private_files'])))
    d.p('**A correction found while the data were gathered.** The function `parse_ref` of `tools/doc_stage3_common.py` split a line '
        '`name : result` at the first “ : ”, so two checks whose names contain “ : ” were not counted; since commit %s it splits such a line at '
        'the last “ : ”, and the documents give 50 checks of `tools/ref_coupled.py` and 38 of `tools/ref_torus_brane.py` (before, 49 and 37).' % dc)
    d.p('**A correction made with the spreadsheet.** GRAVITY_PROVENANCE said that the author’s reference notebook Einstein-Lovelock-7+1-Nash.nb '
        'is not part of the repository; at the author’s request it was added, with its PDF printout, on 27 October 2026 (commit 730a263). The '
        'record now says so.')
    d.h2('%d.3 Verification' % secno)
    rows = []
    if cmp_:
        rows.append(['the stored values of the formulas of the spreadsheet, against an evaluator of their own', '%d of %d equal' % (cmp_[1], cmp_[0])])
    if cc is not None:
        rows.append(['the names and statistics of the commits (`git show --shortstat`)', '%d of %d agree' % (sum(1 for x in cc if x[1] and x[2]), len(cc))])
    if pc is not None:
        rows.append(['the page counts of the PDFs at %s (`pdfinfo`)' % dc, '%d of %d agree' % (sum(1 for x in pc if x[1] == x[2]), len(pc))])
    rows.append(['the formulas of the rewritten paragraphs, in their documents at %s' % dc, '%d of %d found' % (sum(1 for x in fp if x[1]), len(fp))])
    if prc is not None:
        rows.append(['the exit codes and the counts of results of the twelve programs, against this build', '%d of %d agree' % (
            sum(1 for x in prc if x[3]), len(prc))])
    d.table(['check', 'result'], rows, widths=[0.7, 0.3], small=True)
    d.p('The counts of results of a program $P$ are $N_{\\rm True}(P)$ and $N_{\\rm False}(P)$, the numbers of lines of its output that end in '
        '“: True” or “(True)”, respectively “: False” or “(False)”. A loose line is a line whose badness $b=\\min\\big(10000,100(t/s)^3\\big)$ '
        'exceeds 1000, where $t$ is the stretch that the line needs and $s$ the total stretchability of its spaces.')
