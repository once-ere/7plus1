"""Content of 7plus1_status_2026-10-28 (Markdown + LaTeX): the state of the repository github.com/once-ere/7plus1 at commit 102f399 (28 October
2026) -- everything that the spreadsheet 7plus1_status_2026-10-28.xlsx contains (its six sheets as tables and its 35 formulas with their values),
with the formulas of every paragraph that was rewritten, TeX's measure of a loose line and the conventions of the 7+1 project.  Every number is
read from tools/status_2026-10-28.json (doc_status_common).  Every equation used is written in this document."""
from docgen import Doc
from doc_common import signature_block
import doc_status_common as C


def build(today):
    S = C.load()
    dc = S['described_commit']
    rows = C.summary_rows(S)
    fs, wb = C.formulas(S)
    cmp_ = C.stored_comparison(S)
    T = lambda k: dict((r[0], r[1]) for r in rows)[k]
    ndoc = len(S['documents']); pages = sum(d['pages'] for d in S['documents'])
    l0 = sum(d['loose_start'] for d in S['documents']); l1 = sum(d['loose_after_0654dcd'] for d in S['documents'])
    l2 = sum(d['loose_now'] for d in S['documents'])
    ntrue = sum(p['true'] for p in S['programs']); nfalse = sum(p['false'] for p in S['programs'])
    nb = S['notebook']; fr = S['rebuild']
    nfix = sum(1 for f in S['fixes'] if f['how'] in ('Display', 'Code block', 'Reworded'))

    d = Doc(S['title'],
            'The state of github.com/once-ere/7plus1 at commit %s — everything that the spreadsheet %s.xlsx contains, with every formula it uses'
            % (dc, C.NAME),
            ['Repository: github.com/once-ere/7plus1 — prepared for Nash',
             'Commit described: %s of %s PDT (branch %s)' % (dc, C.when(S['described_time']), S['branch']),
             'Spreadsheet: %s.xlsx' % C.NAME, 'Data file: tools/status_2026-10-28.json',
             'Document generated by tools/make_docs.py on ' + today],
            'On 28 October 2026 the documentation of the 7+1 project was completed with the auxiliary torus, the world brane and the radion '
            '(sections 25 and 26 of the notebook 7+1.nb), and every loose line of its %d PDF documents was removed. This document records the state '
            'of the repository after that work, at commit %s: the %d commits of that day up to it, the %d documents with their %d pages and their loose lines '
            '(%d, then %d, now %d), the %d paragraphs that were rewritten, with their formulas, the results of the twelve check programs (%d True, %d '
            'False) and of the %d checks of the notebook (%d True), the comparison of a fresh clone with the commit, and the private files that are '
            'kept out of the repository. It contains the six sheets of the spreadsheet %s.xlsx as tables and its %d formulas with their values; every '
            'number comes from tools/status_2026-10-28.json, the data file of the spreadsheet%s. The conventions of the 7+1 project, TeX’s measure '
            'of a loose line and the functions of the spreadsheet are defined here; every equation used is written in this document.'
            % (ndoc, dc, len(S['commits']), ndoc, pages, l0, l1, l2, nfix, ntrue, nfalse, nb['checks'], nb['true'], C.NAME, len(fs),
               ('; the values that LibreOffice computed and stored in the spreadsheet equal those computed here (%d of %d)' % (cmp_[1], cmp_[0]))
               if cmp_ else ''))

    # ==============================================================================================
    d.h1('1. Results at a glance')
    d.p('The first sheet of the spreadsheet, Summary. Every value is a formula that reads the other sheets (section 8); the last column names the '
        'sheet, and the section of this document that reproduces it.')
    sec = {'Commits': '3', 'Documents': '4', 'Fixes': '5', 'Checks': '6', 'Private files': '7'}
    d.table(['item', 'value', 'where it comes from'],
            [[it, C.num(v), '%s (section %s)' % (src, sec[src.split(',')[0]])] for it, v, src, f in rows],
            widths=[0.5, 0.12, 0.38], small=True)
    d.p('In words: the %d commits of 28 October 2026 up to %s made %s file changes (a file changed in two commits counts twice). The %d documents — each in '
        'Markdown, LaTeX and PDF — have %d pages; the first full build of the day left %d loose lines in them, %d remained after commit 0654dcd, '
        'and none remain: no line is loose, none overflows, and LaTeX reports no error. For this, %d paragraphs were rewritten. The %d check '
        'programs all exit with code 0 and report %d results True and %d False; the %d checks of the notebook 7+1.nb all returned True, with no '
        'message (error) cell. A fresh clone of %s, rebuilt from scratch, reproduces %s Markdown and LaTeX files byte for byte and %s PDFs with the '
        'same text and page count; no private file is on GitHub.'
        % (len(S['commits']), dc, C.num(T('File changes in these commits')), ndoc, pages, l0, l1, nfix, len(S['programs']), ntrue, nfalse,
           nb['checks'], fr['commit'], T('Markdown and LaTeX files identical after a fresh rebuild'),
           T('PDFs with the same text and page count after a fresh rebuild')))

    # ==============================================================================================
    d.h1('2. Conventions')
    d.h2('2.1 The 7+1 spacetime')
    d.p('The 7+1 project constructs the octonions and the Clifford algebra of an eight-dimensional spacetime with the coordinates '
        '$X=(x_0,x_1,\\dots,x_7)$: $x_0$ is time, the direction of the octonion unit $e_0=1$; $x_1,x_2,x_3$ are ordinary space; $x_4,\\dots,x_7$ are '
        'four auxiliary space-like dimensions. Capital indices $A,B$ run over $0,\\dots,7$.')
    signature_block(d, eta=r'\eta', eta71=r'\eta_{71}', gam=r'\Gamma')
    d.h2('2.2 Commits, times and counts')
    d.ul(['A commit is named by the first seven hexadecimal digits of its 40-digit SHA-1 object name in Git (`102f399` for '
          '`%s`); section 3 lists the full names.' % S['described_commit_full'],
          'Times are Pacific Daylight Time (PDT, UTC−7), the time zone of the author’s computer, on which the commits were made; dates are '
          'written year-month-day.',
          'For a commit, "files changed", "lines added" and "lines removed" are the three numbers of `git show --shortstat`: a file counts once per '
          'commit that changes it, and a binary file (a PDF) counts as changed but adds and removes no lines.',
          'A document is one of the %d documentation files of the repository at commit %s; each exists as Markdown (`.md`), LaTeX (`.tex`) and PDF (`.pdf`). Its '
          '"kind" is Main (a document), Symbols (its symbol dictionary) or Provenance (its provenance record); "covers" names the sections of '
          '7+1.nb that it describes; its pages are those that `pdfinfo` reports.' % (ndoc, dc),
          'A document was "changed by" a commit if the commit changed its Markdown, LaTeX or PDF file.'])
    d.h2('2.3 Loose and overflowing lines')
    d.p('TeX sets each line of a paragraph in a box of the line width $w$. The material of the line has a natural width $w_0$, and its spaces '
        'can stretch by at most $s$ (the total stretchability) or shrink by at most $z$ (the total shrinkability) without becoming ugly. When a '
        'line must stretch by $t=w-w_0>0$, TeX measures how bad it is by its badness')
    d.eq(r'b=\min\Big(10000,\ 100\Big(\frac ts\Big)^3\Big)\qquad(s>0),\qquad b=10000\quad(s=0,\ t>0),')
    d.p('rounded to an integer. A LOOSE line — in the log of LaTeX the message `Underfull \\hbox` — is a line whose badness exceeds 1000, the '
        'value of the parameter `\\hbadness` that LaTeX sets: its spaces stretch to more than $10^{1/3}\\approx2.154$ times their stretchability,')
    d.eq(r'\text{loose:}\quad b>1000\iff\frac ts>10^{1/3}\approx2.154 .')
    d.p('An OVERFLOWING line — the message `Overfull \\hbox` — is wider than the line even with all its spaces shrunk, by more than 0.1 pt, the '
        'value of the parameter `\\hfuzz`:')
    d.eq(r'\text{overflowing:}\quad w_0-z-w>0.1\ \text{pt}.')
    d.p('The numbers of loose and overflowing lines of a document are the numbers of the messages `Underfull \\hbox` and `Overfull \\hbox` in '
        'the log of its last LaTeX run (each message is one box: a line of a paragraph or of a table cell); a LaTeX error is a line of that log '
        'that begins with "!". The documents are compiled with `latexmk -xelatex`.')
    d.h2('2.4 The results of the check programs')
    d.p('Each check program prints one line per result. The numbers of results reported True and False by a program $P$ are')
    d.align([r'N_{\rm True}(P)&=\#\{\ell:\ \ell\text{ ends in “: True” or in “(True)”}\},',
             r'N_{\rm False}(P)&=\#\{\ell:\ \ell\text{ ends in “: False” or in “(False)”}\},'])
    d.p('where $\\ell$ runs over the lines of the output of $P$, $\\#$ counts the elements of a set, and spaces between the colon and the word, '
        'and after the word, are allowed. The exit code is the status with which the program ends; 0 means success.')

    # ==============================================================================================
    d.h1('3. The commits of 28 October 2026')
    d.p('The sheet Commits. The four commits of 28 October 2026 up to %s, on the branch %s of %s:' % (dc, S['branch'], S['repository']))
    cr = [[c['hash'], C.when(c['time']), C.num(c['files']), C.num(c['added']), C.num(c['removed'])] for c in S['commits']]
    cr.append(['**Total**', '', '**%s**' % C.num(sum(c['files'] for c in S['commits'])), '**%s**' % C.num(sum(c['added'] for c in S['commits'])),
               '**%s**' % C.num(sum(c['removed'] for c in S['commits']))])
    d.table(['commit', 'date and time (PDT)', 'files changed', 'lines added', 'lines removed'], cr, widths=[0.14, 0.3, 0.18, 0.18, 0.2])
    d.p('What each commit contains:')
    d.ul(['**%s** (`%s`), %s — *%s.* %s.' % (c['hash'], c['full'], C.when(c['time']), C.markup(c['title'], S), C.markup(c['contents'], S))
          for c in S['commits']])
    d.p('Commit %s corrects two check counts that were found while the spreadsheet was being prepared; the spreadsheet and its three documents '
        'were added in the next commit.' % dc)

    # ==============================================================================================
    d.h1('4. The %d documents' % ndoc)
    d.p('The sheet Documents, in two tables. The first gives what each document is; the second gives its loose lines in three builds — the '
        'first full build of the documents on 28 October 2026 (before commit 0654dcd), the rebuild of a fresh clone of 0654dcd, and the rebuild '
        'of a fresh clone of %s ("now") — its overflowing lines and LaTeX errors now, and whether the commits 93c500f and %s changed it.'
        % (fr['commit'], dc))
    d.h2('4.1 What each document is')
    rr = [['`%s`' % x['name'], x['kind'], x['covers'], str(x['pages'])] for x in S['documents']]
    rr.append(['**Total (%d documents)**' % ndoc, '', '', '**%d**' % pages])
    d.table(['document', 'kind', 'covers (sections of 7+1.nb)', 'pages'], rr, widths=[0.4, 0.15, 0.33, 0.12], small=True)
    d.h2('4.2 Loose lines, overflowing lines and errors')
    yn = lambda b: 'yes' if b else 'no'
    rr = [['`%s`' % x['name'], str(x['loose_start']), str(x['loose_after_0654dcd']), str(x['loose_now']), str(x['overfull_now']),
           str(x['errors_now']), yn(x['changed_93c500f']), yn(x['changed_102f399'])] for x in S['documents']]
    tot = lambda k: sum(x[k] for x in S['documents'])
    rr.append(['**Total**', '**%d**' % tot('loose_start'), '**%d**' % tot('loose_after_0654dcd'), '**%d**' % tot('loose_now'),
               '**%d**' % tot('overfull_now'), '**%d**' % tot('errors_now'), '**%d yes**' % tot('changed_93c500f'),
               '**%d yes**' % tot('changed_102f399')])
    d.table(['document', 'loose, first build', 'loose after 0654dcd', 'loose now', 'overflowing now', 'errors now', 'changed by 93c500f',
             'changed by %s' % dc], rr, widths=[0.27, 0.1, 0.1, 0.08, 0.13, 0.08, 0.12, 0.12], small=True)
    n0 = sum(1 for f in S['fixes'] if f['commit'] == '0654dcd' and f['how'] in ('Display', 'Code block', 'Reworded'))
    n1 = sum(1 for f in S['fixes'] if f['commit'] == '93c500f' and f['how'] in ('Display', 'Code block', 'Reworded'))
    d.p('The loose lines of the first build were all in the README and in the documents of the earlier stages; the documents of the auxiliary '
        'torus, the world brane and the radion had none. Commit 0654dcd let code break inside long file names and hashes, set the headings ragged '
        'right and rewrote %d paragraphs, which removed %d of the %d loose lines; commit 93c500f rewrote %d more paragraphs, which removed the '
        'other %d (section 5).' % (n0, l0 - l1, l0, n1, l1))

    # ==============================================================================================
    d.h1('5. The rewritten paragraphs')
    d.p('The sheet Fixes. "How": Line breaking — a change of the typesetting rules; Display — a long inline formula moved into a displayed '
        'equation; Code block — a long piece of code moved into a block of its own; Reworded — the sentence rewritten so that TeX can break its '
        'lines evenly; Correction — a correction of content. Every rewritten paragraph keeps its content.')
    d.table(['#', 'document', 'section of the document', 'how', 'change', 'commit'],
            [[str(i + 1), C.markup(f['document'], S), C.markup(f['section'], S), f['how'], C.markup(f['change'], S), f['commit']]
             for i, f in enumerate(S['fixes'])], widths=[0.05, 0.21, 0.23, 0.11, 0.30, 0.10], small=True)
    d.p('The formulas of the rewritten paragraphs, exactly as the documents write them (a final comma, colon or semicolon that continues the '
        'sentence of the document is written here as a full stop). Rows 1, 12, 13 and 18 contain no formula.')
    C.emit_formulas(d, heading=lambda k, F: '5.%d Row %d, %s: %s' % (k + 1, F['fix'], F['doc'], F['title']))

    # ==============================================================================================
    d.h1('6. The checks')
    d.h2('6.1 The twelve check programs')
    d.p('The sheet Checks, first table: the outputs of the programs in the rebuild of a fresh clone of %s (section 2.4 defines the counts).' % fr['commit'])
    pr = [['`%s`' % p['program'], C.markup(p['checks'], S), str(p['exit_code']), str(p['true']), str(p['false']), p['verdict']] for p in S['programs']]
    pr.append(['**Total (%d programs)**' % len(S['programs']), '**%s**' % C.Evaluator.text(dict(((s, c), v) for s, c, f, v in fs)[('Checks', 'B14')]),
               '', '**%d**' % ntrue, '**%d**' % nfalse, ''])
    d.table(['program', 'what it checks', 'exit code', 'True', 'False', 'verdict'], pr, widths=[0.25, 0.36, 0.07, 0.07, 0.07, 0.18], small=True)
    d.h2('6.2 The notebook 7+1.nb')
    d.p('The notebook contains %d checks `check["name", test]`: %d print their result where they stand, and %d are made by the function '
        '`frameChecks` of section 13.1 of the notebook (nine for each of four metrics) and printed by its summary table. The notebook was '
        'evaluated in a fresh kernel and finished on %s.' % (nb['checks'], nb['printed'], nb['frame'], nb['finished']))
    d.table(['quantity', 'value'], [
        ['checks in the notebook', str(nb['checks'])], ['checks that returned True', str(nb['true'])],
        ['… printed where they stand', str(nb['printed'])], ['… made by `frameChecks` (section 13.1), printed by the summary table', str(nb['frame'])],
        ['message (error) cells', str(nb['messages'])], ['input cells', str(nb['inputs'])], ['output cells', str(nb['outputs'])],
        ['evaluation time (seconds)', '%.3f' % nb['seconds']], ['Wolfram version', nb['wolfram']]], widths=[0.62, 0.38], small=True)
    d.h2('6.3 A fresh clone of %s, rebuilt from scratch' % fr['commit'])
    d.p('The repository was cloned from GitHub into an empty directory, and every document was rebuilt there with `tools/make_docs.py` (which also '
        'runs the twelve programs); the rebuilt files were then compared with the committed ones — Markdown and LaTeX byte for byte, PDF by its '
        'text (`pdftotext`) and its page count (`pdfinfo`), since a PDF also records the time of its creation.')
    d.table(['quantity', 'value'], [
        ['files tracked in the repository', str(fr['tracked'])], ['Markdown and LaTeX files compared', str(fr['mdtex'])],
        ['… identical byte for byte', str(fr['mdtex_same'])], ['PDFs compared', str(fr['pdfs'])],
        ['… with the same text and page count', str(fr['pdfs_same'])], ['documents with layout problems (loose or overflowing lines, errors)',
                                                                         str(fr['layout_problems'])],
        ['other files changed by the rebuild', str(fr['other_changed'])]], widths=[0.62, 0.38], small=True)

    # ==============================================================================================
    d.h1('7. The private files')
    d.p('The sheet Private files: files of the author that are in the working folder of the project but are not published. Their names are not '
        'given here.')
    d.table(['file', 'what it is', 'on GitHub?', 'how it is kept out'],
            [[C.markup(p['file'], S), C.markup(p['what'], S), p['on_github'], C.markup(p['how'], S)] for p in S['private_files']],
            widths=[0.22, 0.36, 0.12, 0.3], small=True)
    d.p('`.gitignore` lists the files that Git does not track in every clone of the repository; `.git/info/exclude` lists files that Git does not '
        'track in one working folder only, and is itself never published. The check: `git ls-files` of the fresh clone of %s lists none of '
        'these files.' % fr['commit'])

    # ==============================================================================================
    d.h1('8. The formulas of the spreadsheet')
    d.h2('8.1 Cells, ranges and functions')
    d.p('A cell is named by its column letter and its row number (`B5`: column B, row 5); `Commits!E6` is the cell E6 of the sheet Commits, and '
        'a sheet name with a space is quoted (`\'Private files\'!C2`). A range `A2:A5` is the rectangle of cells from A2 to A5. With $R$ a range, '
        '$v(c)$ the value of the cell $c$, $x$ a value and $y$ a value, the functions and operators of the spreadsheet are')
    d.align([r'\mathrm{SUM}(R)&=\sum_{c\in R,\ v(c)\ \text{a number}}v(c),\qquad \mathrm{COUNTA}(R)=\#\{c\in R:\ v(c)\ \text{not empty}\},',
             r'\mathrm{COUNTIF}(R,x)&=\#\{c\in R:\ v(c)=x\}\quad(\text{texts compared without regard to case}),',
             r'x+y&=\text{the sum},\qquad x\,\&\,y=\text{the text of }x\text{ followed by the text of }y .'])
    d.h2('8.2 The %d formulas and their values' % len(fs))
    d.p('In the order of the sheets. The values are computed here, from the data file, by an evaluator of these functions; the same values are '
        'stored in the spreadsheet.')
    d.table(['sheet', 'cell', 'formula', 'value'], [[s, c, '`%s`' % f, C.num(v)] for s, c, f, v in fs], widths=[0.13, 0.07, 0.6, 0.2], small=True)
    if cmp_:
        d.p('**Check.** The spreadsheet stores, for each formula, the value that LibreOffice computed when it saved the file; %d of the %d stored '
            'values equal the values of the table.%s' % (cmp_[1], cmp_[0], '' if not cmp_[2] else ' Different: ' + '; '.join(
                '%s!%s (stored %r, computed %r)' % (s, c, st, v) for s, c, f, v, st in cmp_[2])))

    # ==============================================================================================
    d.h1('9. How to reproduce')
    d.p('**The spreadsheet.** The command below writes `%s.xlsx` from `tools/status_2026-10-28.json` with openpyxl; if LibreOffice is installed, '
        'it then opens and saves the file in headless mode, which computes and stores the value of every formula, and it checks that no formula '
        'gives an error:' % C.NAME)
    d.code('python3 tools/make_status_xlsx.py', 'text')
    d.p('**The documents.** This document, its symbol dictionary and its provenance record (Markdown, LaTeX, PDF); the command runs the twelve '
        'check programs first:')
    d.code('python3 tools/make_docs.py %s \\\n    %s_SYMBOLS %s_PROVENANCE' % (C.NAME, C.NAME, C.NAME), 'text')
    d.p('**The numbers of the data file** come from the repository — the commits (section 3), the changed documents and the pages:')
    d.code('git show --shortstat --format= <commit>\ngit show --name-only --format= <commit>\ngit show %s:<document>.pdf > x.pdf && pdfinfo x.pdf' % dc,
           'text')
    d.p('— and from the logs of LaTeX in `build/docs` (the loose lines), `build/docs/runs.json` (the outputs of the programs), the evaluation '
        'record `tools/eval_log_7p1.txt` and the evaluated 7+1.nb (the notebook), and a fresh clone (section 6.3).')
    return C.typographic(d)
