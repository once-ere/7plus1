from docgen import Doc
from doc_stage3_common import fmt
from doc_ks_gravity import compare, max_rel


def build(D, today, runs):
    ck = D['checks']['ks']; refd = D['ref'].get('ks', ('', '', {})); ref = refd[2]
    nck = len(ck); nok = sum(1 for c in ck if c[1] == 'True')
    rb = [(k, v) for k, v in ref.items() if v in ('True', 'False')]
    d = Doc('The self-coupled dirac16complex in gravitational fields: provenance',
            'Sources, decisions, derivations and the verification record of the nine-channel self-coupling, the Fierz matrix, the '
            'covariant nonlinear field equation and the Kohn–Sham theory of dirac16complex in the three epochs — sections 15–16 of the '
            'notebook 7+1.nb',
            ['Repository: github.com/once-ere/7plus1 — prepared for Nash',
             'Notebook: 7+1.nb (Wolfram Language 15.0.1)', 'Document generated by tools/make_docs.py on ' + today],
            'This record states what was asked, what was used, every decision taken with the equation behind it, how each result was '
            'derived and how it was checked: the %d checks of sections 15–16 of 7+1.nb (%d True), the %d boolean checks of the '
            'independent Python program tools/ref_ks_gravity.py (%d True), the comparison of every number printed by both programs, '
            'and the SHA-256 hashes of the files.' % (nck, nok, len(rb), sum(1 for k, v in rb if v == 'True')))

    d.h1('1. The task')
    d.p('This stage of the project asked (summarized; the original wording is the author’s private working material):')
    d.ol(['a GENERALIZED self-coupling of the 16-component field dirac16complex, beyond the four contact couplings (scalar, pseudoscalar, '
          'vector, axial) of the earlier Kohn–Sham theory of the notebook;',
          'the Kohn–Sham theory of dirac16complex in GRAVITATIONAL fields, with the canonical spin connection coupling gravity to the field, '
          'in the primordial epoch (near $x_0=0$), the modern epoch and the far future;',
          'everything on the 7+1 spacetime of this project — one time coordinate $x_0$, seven space coordinates $x_1,\\dots,x_7$, metric '
          'signature $(+,-,\\dots,-)$ — with the ideas (not the 4+4 metric) of the repository github.com/once-ere/Dirac_claude;',
          'for every documentation file a companion provenance file and a symbol file, in Markdown and LaTeX with PDFs; no document '
          'refers the reader to another one; every equation used is written in the document that uses it.'])

    d.h1('2. Inputs')
    d.h2('2.1 Objects of the earlier sections of 7+1.nb')
    d.p('Used unchanged: the real Dirac matrices `Γ17[A]`, `Γ17up[A]`, the metric `η17`, the chirality `χ17` $=i\\,\\Gamma_0\\Gamma_1\\cdots\\Gamma_7$, '
        'the chiral basis `EL`, `ER`, the Hamiltonian matrices `αD[j]`, `βD`, the curvature engine and the frame data of the cosmological '
        'metric (`fdCos`), the closed forms of the Lovelock tensors of the cosmological metric (`ECos`, with the rewriting `toH` in terms of '
        '$H_a,H_b,H_a\',H_b\'$), and the Hartree couplings and saturation state of the uniform matter of section 8.7 of the notebook:')
    d.align([r'\Gamma_0&=\begin{pmatrix}0&1_8\\1_8&0\end{pmatrix},\quad \Gamma_i=\begin{pmatrix}\tau^O_i&0\\0&-\tau^O_i\end{pmatrix},\quad '
             r'\chi=i\,\Gamma_0\Gamma_1\cdots\Gamma_7,',
             r'E_L&=\tfrac1{\sqrt2}\begin{pmatrix}1_8\\-i1_8\end{pmatrix},\quad E_R=\tfrac1{\sqrt2}\begin{pmatrix}-i1_8\\1_8\end{pmatrix},',
             r'G_S&=-100000,\quad G_V=10000\ \ (m=1),',
             r'k_{F,\rm sat}&=0.75663615070149289469\ldots\ \ \text{(where } E/A \text{ is minimal at } a=b=1).'])
    d.h2('2.2 Software')
    vv = D.get('versions', {})
    d.ul(['Wolfram Language 15.0.1 (front end WolframNB.exe), with the standard package NumericalDifferentialEquationAnalysis (its function `GaussianQuadratureWeights`) for the Gauss–Legendre '
          'nodes.',
          'Python %s with numpy %s, scipy %s, sympy %s (the independent program).' % (vv.get('python', '?'), vv.get('numpy', '?'),
                                                                                 vv.get('scipy', '?'), vv.get('sympy', '?')),
          'Textbook results, each derived and checked here: Fierz rearrangement (M. Fierz, Z. Phys. 104 (1937) 553), Hohenberg–Kohn and '
          'Kohn–Sham (Phys. Rev. 136 (1964) B864; 140 (1965) A1133), relativistic mean-field matter (J. D. Walecka, Ann. Phys. 83 (1974) 491).'])

    d.h1('3. Decisions')
    d.table(['#', 'decision', 'reason / equation'], [
        ['1', 'basis of the 256 matrices: $\\Theta^K=i^{\\sigma_r}\\Gamma^{A_1}\\cdots\\Gamma^{A_r}$, $\\sigma_r=\\frac{r(r-1)}2\\bmod2$',
         '$(\\Gamma_0\\Gamma^{A_1}\\cdots\\Gamma^{A_r})^\\dagger=(-1)^{r(r-1)/2}\\,\\Gamma_0\\Gamma^{A_1}\\cdots\\Gamma^{A_r}$ (reversing $r$ distinct anticommuting factors); the phase $i^{\\sigma_r}$ makes $\\Gamma_0\\Theta^K$ Hermitian, so every bilinear is real (section 4)'],
        ['2', 'the self-coupling is organized by rank, one coupling $g_r$ per rank', 'each rank is a Lorentz-invariant class (the generators $\\frac14[\\Gamma^A,\\Gamma^B]$ map products of rank $r$ to rank $r$)'],
        ['3', 'the four couplings of section 8 are identified as $g_0=g_S$, $g_1=g_V$, $g_7=-g_A$, $g_8=-g_P$', '$I_8=-(\\bar\\psi i\\chi\\psi)^2$ and $I_7=-(\\bar\\psi\\Gamma^A\\chi\\psi)(\\bar\\psi\\Gamma_A\\chi\\psi)$'],
        ['4', 'exchange is folded into the direct terms by the Fierz matrix', '$E_x=-\\sum_{r,s}\\frac{g_r}2F_{rs}D_s$, hence $G=(1-F^{\\mathsf T})g$'],
        ['5', 'uniform matter: spin-saturated, no Dirac sea, Hartree–Fock couplings $G_S=G_0$, $G_V=G_1$', 'only $D_0=\\rho_S^2$ and $D_1=\\rho^2$ are non-zero for $R=(\\rho_S1+\\rho\\Gamma_0)/16$'],
        ['6', 'comoving Fermi ball: the comoving momenta are conserved by a homogeneous expansion', 'the modes $e^{i(\\vec p\\cdot\\vec x+\\vec q\\cdot\\vec y)}$ keep $\\vec p,\\vec q$; the physical momenta are $\\vec p/a$, $\\vec q/b$'],
        ['7', 'the comoving Fermi momentum is the flat-space saturation value', 'the matter starts (at $a=b=1$) in its ground state at zero pressure'],
        ['8', 'adiabatic (instantaneous) Kohn–Sham state', 'valid when $H_a,H_b\\ll$ orbital energies; the pair creation of the epochs measures the departures'],
        ['9', 'Gauss–Legendre quadrature with 96 × 64 nodes in $(k,\\theta)$', 'smooth integrands; the flat limit reproduces the closed forms of section 8.7 to $10^{-11}$'],
        ['10', 'the 00 equation is imposed on the initial data only', 'it is a constraint without second derivatives; its preservation is a check of the whole system'],
        ['11', 'NDSolve with explicit Runge–Kutta of order 8 and InterpolationOrder → All', 'without it the interpolation between steps (order 3) showed an apparent constraint violation of $2\\times10^{-6}$'],
    ], widths=[0.055, 0.475, 0.47], small=True)

    d.h1('4. Derivations')
    d.p('**Reality of the bilinears.** $\\Gamma_0\\Gamma^{A\\dagger}\\Gamma_0=\\Gamma^A$, so $(\\Gamma_0\\Gamma^{A_1}\\cdots\\Gamma^{A_r})^\\dagger='
        '\\Gamma^{A_r\\dagger}\\cdots\\Gamma^{A_1\\dagger}\\Gamma_0=\\Gamma_0\\Gamma^{A_r}\\cdots\\Gamma^{A_1}=(-1)^{r(r-1)/2}\\Gamma_0\\Gamma^{A_1}\\cdots\\Gamma^{A_r}$ '
        '(distinct indices anticommute). Multiplying by $i^{\\sigma_r}$ with $\\sigma_r=\\frac{r(r-1)}2\\bmod2$ compensates the sign: '
        '$(i^{\\sigma_r})^*(-1)^{r(r-1)/2}=i^{\\sigma_r}$.')
    d.p('**Fierz matrix.** Completeness, $\\sum_K(\\Theta_K)_{cd}(\\Theta^K)_{ab}=16\\delta_{ad}\\delta_{bc}$, gives '
        '$\\sum_{K\\in r}(a\\Theta_Kb)(c\\Theta^Kd)=\\sum_JC_{rJ}(a\\Theta_Jd)(c\\Theta^Jb)$ with $C_{rJ}=\\frac1{256}\\sum_{K\\in r}\\mathrm{tr}(\\Theta_K\\Theta_J\\Theta^K\\Theta^J)$. '
        'Moving $\\Gamma^{A}$ through a product of $s$ distinct $\\Gamma$’s gives $(-1)^s$ if $A$ is not among them and $(-1)^{s-1}$ if it is; for '
        '$K$ of rank $r$ sharing $l$ indices with $J$ the sign is $(-1)^{rs-l}$, and there are $\\binom sl\\binom{8-s}{r-l}$ such $K$:')
    d.eq(r'F_{rs}=\frac{16}{256}\sum_l(-1)^{rs-l}\binom{s}{l}\binom{8-s}{r-l}=\frac1{16}\sum_l(-1)^{rs-l}\binom{s}{l}\binom{8-s}{r-l}.')
    d.p('**Densities of uniform matter.** A 16-component field has 8 positive-energy states per momentum, so $\\rho=8\\int\\frac{d^7k}{(2\\pi)^7}$ '
        'over the Fermi ball (comoving, divided by the comoving volume factor $a^3b^4$). With $k_a=k\\cos\\theta$, $k_b=k\\sin\\theta$:')
    d.eq(r'd^3k_a\,d^4k_b=(4\pi)(2\pi^2)\,k^6\cos^2\theta\sin^3\theta\,dk\,d\theta,\qquad \frac{8\cdot8\pi^3}{(2\pi)^7}=\frac1{2\pi^4},\\ '
         r'\int_0^{\pi/2}\cos^2\theta\sin^3\theta\,d\theta=\frac2{15},\qquad \rho=\frac{k_F^7}{105\pi^4a^3b^4}.')
    d.p('The kinetic pressures are the momentum flux per direction: three ordinary directions share $k_a^2/a^2$, four auxiliary directions '
        'share $k_b^2/b^2$, which gives $p_a=\\langle k^2\\cos^2\\theta/(3a^2\\omega)\\rangle+\\Pi$ and $p_b=\\langle k^2\\sin^2\\theta/(4b^2\\omega)\\rangle+\\Pi$; '
        'the interaction pressure is $\\Pi=\\rho\\,\\partial\\varepsilon_{\\rm int}/\\partial\\rho-\\varepsilon_{\\rm int}$ of the mean-field energy '
        '$\\varepsilon_{\\rm int}=-\\frac{(M-m)^2}{2G_S}+\\frac{G_V}2\\rho^2$ at fixed $M$.')
    d.p('**Conservation.** $\\varepsilon(a,b,M)$ is stationary in $M$ (that is the gap equation), so $\\varepsilon\'=\\partial_a\\varepsilon\\,a\'+\\partial_b\\varepsilon\\,b\'$; '
        'differentiating the comoving integrals ($\\rho\\propto a^{-3}b^{-4}$, $\\partial_a\\omega=-k^2\\cos^2\\theta/(a^3\\omega)$) gives')
    d.eq(r"\varepsilon'=-3H_a(\varepsilon+p_a)-4H_b(\varepsilon+p_b).")
    d.p('**Constraint preservation.** The Lovelock tensors are divergence-free for every metric, $\\nabla_\\mu E^{(k)\\mu}{}_\\nu=0$; for the cosmological '
        'metric the $\\nu=0$ component reads $\\frac{d}{dx_0}E^{(k)0}{}_0+3H_a(E^{(k)0}{}_0-E^{(k)1}{}_1)+4H_b(E^{(k)0}{}_0-E^{(k)4}{}_4)=0$. With '
        'the 11 and 44 equations imposed and the conservation law above, the 00 equation therefore holds at all times if it holds initially.')

    d.h1('5. Verification')
    lg = D.get('log', {})
    d.p('**Evaluation of 7+1.nb**: Wolfram %s; finished %s; message cells %s. The checks of sections 15–16:' % (
        lg.get('version', '15.0.1'), lg.get('finished', '?'), lg.get('message cells', '?')))
    d.table(['#', 'check', 'result', 'section'],
            [[str(i + 1), '`' + c[0].replace('`', "'") + '`', c[1], (c[3][:4] if c[3] else c[2][:3])] for i, c in enumerate(ck)],
            widths=[0.055, 0.745, 0.08, 0.12], small=True)
    d.p('**The independent Python program** tools/ref_ks_gravity.py — its boolean checks:')
    d.table(['#', 'check', 'result'], [[str(i + 1), '`' + k.replace('`', "'") + '`', v] for i, (k, v) in enumerate(rb)],
            widths=[0.055, 0.825, 0.12], small=True)
    d.p('**Numbers printed by both programs** (relative differences):')
    rows = []
    for lab, a, b in compare(D):
        r = max_rel(a, b)
        rows.append([lab, str(len(a)), fmt(r, 2) if r is not None else '—'])
    d.table(['quantity', 'values', 'max. relative difference'], rows, widths=[0.6, 0.15, 0.25])
    dc = D.get('doc_checks', {})
    if dc:
        d.p('**Checks made while generating the documents:** ' + '; '.join('%s: %s' % (k, v) for k, v in dc.items()) + '.')
    d.p('**SHA-256 of the files** (at the time this document was generated):')
    d.code('\n'.join('%-34s %s' % (f, h) for f, h in D.get('sha', {}).items()), 'text')
    for title, out, *rest in (runs or []):
        if 'ref_ks_gravity' in title:
            d.p('**Output of %s** (complete):' % title)
            d.code(out, 'text')
    return d
