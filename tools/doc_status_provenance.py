"""Content of 7plus1_status_2026-10-28_PROVENANCE (Markdown + LaTeX): where every number of the spreadsheet 7plus1_status_2026-10-28.xlsx and of
its document comes from -- the task, the sources of the data, the decisions, the history of the spreadsheet, how it is built and how it was
checked (the checks are recomputed at every build from the repository, the evaluated notebook and the outputs of the check programs).
Self-contained: every equation used is written here."""
import os, sys, platform
from docgen import Doc
from doc_common import signature_provenance, all_checks
import doc_status_common as C

FIRST_VERSION_SHA = '179f155ac681ae0f3d7d283dc1e427e9dd4badbf2b3f2198090059f2a38d0b83'


def build(D, today, runs):
    S = C.load()
    dc = S['described_commit']; fr = S['rebuild']; nb = S['notebook']
    fs, wb = C.formulas(S)
    cmp_ = C.stored_comparison(S)
    cc = C.commit_checks(S); pc = C.page_checks(S); chc = C.changed_checks(S)
    fp = C.formula_presence(dc); prc = C.program_checks(S, runs)
    d = Doc(S['title'] + ': provenance',
            'The task, the sources of every number, the decisions, the history, the building and the verification of the spreadsheet %s.xlsx and '
            'of the document on the state of the repository at commit %s' % (C.NAME, dc),
            ['Repository: github.com/once-ere/7plus1 — prepared for Nash',
             'Commit described: %s of %s PDT (branch %s)' % (dc, C.when(S['described_time']), S['branch']),
             'Document generated by tools/make_docs.py on ' + today],
            'This record states what was asked, where every number of the spreadsheet %s.xlsx comes from, every decision taken, how the version '
            'in the repository differs from the first version of the spreadsheet, how the spreadsheet and its three documents are built, and how '
            'they were checked: the %d stored formula values against an evaluator of their own, the four commits, the %d page counts and the '
            'changed documents against the repository, the %d quoted formulas against their documents, and the counts of the twelve check '
            'programs and of the notebook against the outputs of this build. Every equation used is written here.'
            % (C.NAME, len(fs), len(S['documents']), len(C.FORMULAS)))

    # ------------------------------------------------------------------------------------------------
    d.h1('1. The task')
    d.p('On 28 October 2026 the author asked for the following (summarized; the original wording is the author’s private working material and '
        'is not reproduced):')
    d.ol(['Remove the slightly loose lines that remained in the older PDF documents, then finish and push all stages.',
          'Create a spreadsheet from the report on that work.',
          'Confirm that all stages are finished, pushed and verified, or complete them.',
          'Add the spreadsheet %s.xlsx to the repository and push it.' % C.NAME])
    d.p('The standing rules of the project apply: every documentation file has a companion provenance file and a symbol file, in Markdown and '
        'LaTeX, compiled to PDF; no file refers the reader to another documentation, provenance or symbol file; every equation that is created or '
        'used is written in the file that uses it. The repository’s .gitignore is respected.')
    d.p('**Interpretation.** In the repository the spreadsheet is a document like the others, so it gets a document that contains everything it '
        'contains (every sheet as a table, every formula with its value), a symbol dictionary and this provenance record. Its numbers are kept in '
        'a data file, `tools/status_2026-10-28.json`, from which a program, `tools/make_status_xlsx.py`, writes the spreadsheet, so that it can be '
        'rebuilt and checked. The version in the repository is written for its readers: it describes the commit %s, refers to no conversation, '
        'and does not name the private files.' % dc)
    d.h2('1.1 The signature: the author’s explanation of 27 October 2026')
    signature_provenance(d, eta=r'\eta', eta71=r'\eta_{71}', gam=r'\Gamma')

    # ------------------------------------------------------------------------------------------------
    d.h1('2. Where every number comes from')
    d.table(['data', 'source', 'how it was obtained'], [
        ['the commits: names, times, titles', 'the history of the repository', '`git log`; the full names with `git rev-parse`'],
        ['files changed, lines added, lines removed', 'the history of the repository', '`git show --shortstat --format= <commit>`'],
        ['what each commit contains', 'the commit messages', 'summarized'],
        ['the documents, their kinds and what they cover', 'the list of documents of `tools/make_docs.py`', '—'],
        ['pages', 'the PDFs of the commit %s' % dc, '`pdfinfo`'],
        ['loose lines, first build', 'the logs of LaTeX of the first full build of the documents on 28 October 2026 (09:40 PDT, before commit '
         '0654dcd)', 'the messages `Underfull \\hbox`, counted per document'],
        ['loose lines after 0654dcd', 'the logs of the rebuild of a fresh clone of 0654dcd (10:10 PDT)', 'the same'],
        ['loose lines, overflowing lines and errors now', 'the logs of the rebuild of a fresh clone of %s (13:35 PDT)' % fr['commit'],
         'the messages `Underfull \\hbox`, `Overfull \\hbox` and the lines that begin with "!"'],
        ['changed by 93c500f, by %s' % dc, 'the history of the repository', '`git show --name-only --format= <commit>`'],
        ['the rewritten paragraphs', 'the changes of the commits 0654dcd and 93c500f and the message of 93c500f', '`git diff`, read paragraph by paragraph'],
        ['the results of the twelve programs', 'their outputs in the rebuild of the fresh clone of %s (build/docs/runs.json of that clone)' % fr['commit'],
         'the exit codes, and the counts (2.1) below'],
        ['the notebook', '`tools/eval_log_7p1.txt` and the evaluated 7+1.nb', 'the record of the evaluation; the parse of the notebook by '
         '`tools/verify_7p1_nb.py`'],
        ['the fresh clone', 'a clone of github.com/once-ere/7plus1 at %s, rebuilt from scratch' % fr['commit'], 'Markdown and LaTeX compared byte for '
         'byte, PDFs by `pdftotext` and `pdfinfo`'],
        ['the private files', '`git ls-files` of the fresh clone; `.gitignore`; `.git/info/exclude` on the author’s computer', '—'],
    ], widths=[0.27, 0.4, 0.33], small=True)
    d.p('The counts of the results of a program $P$, with $\\ell$ running over the lines of its output and $\\#$ counting the elements of a set:')
    d.align([r'N_{\rm True}(P)&=\#\{\ell:\ \ell\text{ ends in “: True” or in “(True)”}\},&&(2.1)',
             r'N_{\rm False}(P)&=\#\{\ell:\ \ell\text{ ends in “: False” or in “(False)”}\}'])
    d.p('(spaces between the colon and the word, and after the word, are allowed). A loose line is a line whose badness $b$ exceeds 1000, an '
        'overflowing line one that is wider than the line width $w$ by more than 0.1 pt even with all its spaces shrunk; with $t=w-w_0$ the '
        'stretch that a line of natural width $w_0$ needs, $s$ its total stretchability and $z$ its total shrinkability,')
    d.eq(r'b=\min\Big(10000,\ 100\Big(\frac ts\Big)^3\Big),\qquad \text{loose}\iff b>1000,\qquad \text{overflowing}\iff w_0-z-w>0.1\ \text{pt}.\qquad(2.2)')

    # ------------------------------------------------------------------------------------------------
    d.h1('3. Decisions')
    d.ol(['**A data file and a program**, not a spreadsheet made by hand: `tools/status_2026-10-28.json` holds every number, and '
          '`tools/make_status_xlsx.py` writes the spreadsheet from it; the three documents read the same data file.',
          '**Every total and every value of the sheet Summary is a formula** (%d formulas in all), so that the spreadsheet shows how each number '
          'follows from the tables.' % len(fs),
          '**The values of the formulas are stored in the file.** openpyxl writes formulas without values; LibreOffice, run without a window, opens '
          'and saves the file, which computes and stores every value, so that a viewer that does not compute shows them too.',
          '**The private files are not named**; they are described as the documents of the project describe them (a printout of an e-mail of the '
          'author on the radion; the author’s private notes on vielbeins in $n$ dimensions; a third private PDF).',
          '**Times are PDT**, the time zone of the author’s computer, on which the commits were made.',
          '**"Now" is the rebuild of a fresh clone of %s**, the most demanding test: only what is published is used.' % fr['commit'],
          '**The documents reproduce the spreadsheet entirely** — every sheet as a table and every formula with its value — so that they can be '
          'read without it.',
          '**Row 18 of the sheet Fixes** names the eight documents whose check counts changed in %s; a ninth, DIRAC16COMPLEX_PROVENANCE, changed '
          'only in the SHA-256 of `tools/doc_stage3_common.py` that it records, and is marked changed in the sheet Documents.' % dc])
    d.p('**The correction found while the data were gathered.** The function `parse_ref` of `tools/doc_stage3_common.py` read a line '
        '`name : result` of the output of a program by splitting it at the FIRST " : ". Two checks have names that contain " : " themselves — '
        'in `tools/ref_coupled.py` a ratio `alpha2 E2 : alpha3 E3 : kappa eps -> 9/4 : -5/4 : 1`, in `tools/ref_torus_brane.py` the set '
        '`#{n in Z^4 : |n|^2 = k}` — so their results were read as text, not as True, and the documents gave 49 and 37 checks instead of 50 and 38. '
        'Commit %s splits a line that ends in " : True" or " : False" at the LAST " : " instead; the counts (2.1), which the spreadsheet uses, were '
        'right from the start.' % dc)

    # ------------------------------------------------------------------------------------------------
    d.h1('4. The history of the spreadsheet')
    d.p('A first version of the spreadsheet was made on 28 October 2026 from the same data and delivered to the author, who saved it in the '
        'working folder of the project (SHA-256 `%s`). The version in the repository was written by `tools/make_status_xlsx.py`. The two were '
        'compared cell by cell: every number and every computed value is the same; the differences are of wording and layout only:' % FIRST_VERSION_SHA)
    d.ul(['Summary: the subtitle names the commit described and its time; the first two items are called "Commit described (the latest when the '
          'spreadsheet was made)" and "Commits of 28 October 2026 up to the commit described" (before: "Latest commit", "Commits since the radion '
          'stage began").',
          'Commits: three descriptions of contents are reworded, and the note says that the spreadsheet and its documents were added in the next '
          'commit, instead of referring to the conversation in which the first version was made.',
          'Documents: the note defines the first build precisely (the first full build of 28 October 2026, before commit 0654dcd).',
          'Fixes: the modifier letters of $\\Theta^K$, $\\sigma_r$ and $U^{\\mathsf T}hU$ are written with `^` and `_` (`Θ^K`, `σ_r`, `U^T h U`), '
          'because some fonts lack them; row 18 names the eight documents and the ninth; the column Document is wider.',
          'Checks: the note states the rule (2.1) by which the results are counted.',
          'Private files: written in the third person and without the names of the files; two columns are wider.'])

    # ------------------------------------------------------------------------------------------------
    d.h1('5. How the spreadsheet and its documents are built')
    import importlib
    try:
        oxl = importlib.import_module('openpyxl').__version__
    except Exception:
        oxl = 'not installed'
    d.ol(['`python3 tools/make_status_xlsx.py` reads the data file and writes the six sheets with openpyxl (%s when this record was generated, '
          'Python %s): Arial 10, headers in white on dark teal, the header row kept in view when scrolling (in Documents also the first column, '
          'in Summary the first four rows), landscape printing one page wide.' % (oxl, platform.python_version()),
          'If LibreOffice is installed, the program converts the file with `soffice --headless --convert-to "xlsx:Calc MS Excel 2007 XML"` (with a '
          'private user profile in a temporary folder) and replaces it by the result: LibreOffice computes and stores the value of every formula '
          'and keeps the formulas. The spreadsheet in the repository records the application that saved it: `%s`.' % (C.xlsx_application() or '—'),
          'The program reads the computed values back and fails if a formula has no value or an error value (a text that begins with "#").',
          '`python3 tools/make_docs.py` writes the document, its symbol dictionary and this record with `tools/doc_status.py`, '
          '`tools/doc_status_symbols.py` and `tools/doc_status_provenance.py`, which take their data from `tools/doc_status_common.py`; that '
          'module reads the data file, rebuilds the workbook in memory and evaluates its formulas with an evaluator of its own (section 6.1).'])

    # ------------------------------------------------------------------------------------------------
    d.h1('6. Verification')
    d.p('Every check of this section is recomputed whenever this record is generated.')
    d.h2('6.1 The formulas of the spreadsheet')
    d.p('The evaluator of `tools/doc_status_common.py` implements the functions and operators that the spreadsheet uses; with $R$ a range of cells, '
        '$v(c)$ the value of the cell $c$ and $x$, $y$ values:')
    d.align([r'\mathrm{SUM}(R)&=\sum_{c\in R,\ v(c)\ \text{a number}}v(c),\qquad \mathrm{COUNTA}(R)=\#\{c\in R:\ v(c)\ \text{not empty}\},',
             r'\mathrm{COUNTIF}(R,x)&=\#\{c\in R:\ v(c)=x\}\quad(\text{texts compared without regard to case}),',
             r'x\,\&\,y&=\text{the text of }x\text{ followed by the text of }y .'])
    if cmp_:
        d.p('It evaluates the %d formulas of the workbook that `tools/make_status_xlsx.py` makes from the data file; the values that LibreOffice '
            'stored in the spreadsheet equal them for **%d of %d** formulas.%s' % (cmp_[0], cmp_[1], cmp_[0], '' if not cmp_[2] else ' Different: ' +
            '; '.join('%s!%s' % (s, c) for s, c, f, v, st in cmp_[2])))
    else:
        d.p('The spreadsheet is not present in this checkout; its stored values could not be compared.')
    d.table(['sheet', 'cell', 'formula', 'value'], [[s, c, '`%s`' % f, C.num(v)] for s, c, f, v in fs], widths=[0.13, 0.07, 0.6, 0.2], small=True)
    d.h2('6.2 The data file against the repository')
    rows = []
    if cc is not None:
        rows.append(['the full names of the four commits', '%d of %d agree' % (sum(1 for x in cc if x[1]), len(cc))])
        rows.append(['files changed, lines added, lines removed (`git show --shortstat`)', '%d of %d agree: %s' % (
            sum(1 for x in cc if x[2]), len(cc), '; '.join('%s %d, %d, %d' % ((x[0],) + x[3]) for x in cc))])
    else:
        rows.append(['the commits', 'git is not available'])
    if pc is not None:
        rows.append(['the page counts of the %d PDFs at %s (`git show %s:<document>.pdf`, `pdfinfo`)' % (len(pc), dc, dc),
                     '%d of %d agree; %d pages in all' % (sum(1 for x in pc if x[1] == x[2]), len(pc), sum(x[2] or 0 for x in pc))])
    else:
        rows.append(['the page counts', 'git or pdfinfo is not available'])
    if chc is not None:
        for c, marked, actual, ok in chc:
            rows.append(['the documents changed by %s (`git show --name-only`)' % c, '%d marked, %d changed: %s' % (marked, actual,
                         'the same documents' if ok else 'DIFFERENT')])
    else:
        rows.append(['the changed documents', 'git is not available'])
    d.table(['check', 'result'], rows, widths=[0.55, 0.45], small=True)
    d.h2('6.3 The quoted formulas against their documents')
    d.p('Each formula of the rewritten paragraphs (section 6.5) must occur, character for character, in the Markdown file of its document at the '
        'commit %s:' % dc)
    d.table(['row', 'document', 'strings found', 'source'], [[str(F['fix']), '`%s`' % F['doc'], '%d of %d' % (k, n), '`%s`' % src]
                                                          for F, ok, n, k, src in fp], widths=[0.07, 0.33, 0.14, 0.46], small=True)
    d.p('**%d of %d** formulas found.' % (sum(1 for x in fp if x[1]), len(fp)))
    d.h2('6.4 The checks against this build')
    if prc is not None:
        d.p('The exit codes and the counts (2.1) of the twelve programs, recounted from their outputs in this build of the documents, against the '
            'data file (exit code, True, False):')
        d.table(['program', 'data file', 'this build', 'agree'], [['`%s`' % p, '%s, %s, %s' % w, ('%s, %s, %s' % g) if g else 'not run', 'yes' if ok else 'NO']
                                                               for p, w, g, ok in prc], widths=[0.4, 0.2, 0.2, 0.2], small=True)
        d.p('**%d of %d** programs agree.' % (sum(1 for x in prc if x[3]), len(prc)))
    else:
        d.p('The outputs of the programs are not available to this build.')
    nbi = D.get('nb') or {}
    lg = D.get('log') or {}
    try:
        allc = all_checks(D)
    except Exception:
        allc = []
    nrows = [['input cells', str(nb['inputs']), str(nbi.get('inputs', '—'))],
             ['output cells', str(nb['outputs']), str(nbi.get('outputs', '—'))],
             ['message cells', str(nb['messages']), str(nbi.get('messages', '—'))],
             ['checks printed where they stand', str(nb['printed']), str(len(nbi.get('checks', [])))],
             ['all checks (with those of `frameChecks`)', str(nb['checks']), str(len(allc)) if allc else '—'],
             ['checks that returned True', str(nb['true']), str(sum(1 for c in allc if c[1] == 'True')) if allc else '—'],
             ['evaluation time (seconds)', '%.3f' % nb['seconds'], lg.get('seconds', '—')]]
    agree = all(a[1] == a[2] for a in nrows)
    d.p('The notebook: the data file against the evaluated 7+1.nb as this build parses it, and against its evaluation record:')
    d.table(['quantity', 'data file', 'this build'], nrows, widths=[0.5, 0.25, 0.25], small=True)
    d.p('**%s.**' % ('All seven agree' if agree else 'NOT ALL AGREE'))
    d.p('The comparison of the fresh clone of %s with the commit (%d tracked files; %d of %d Markdown and LaTeX files identical; %d of %d PDFs '
        'with the same text and page count; %d documents with layout problems; %d other files changed) is the record of that check, which was '
        'made once, on 28 October 2026 at 13:35 PDT.' % (fr['commit'], fr['tracked'], fr['mdtex_same'], fr['mdtex'], fr['pdfs_same'], fr['pdfs'],
                                                        fr['layout_problems'], fr['other_changed']))
    d.h2('6.5 The formulas whose presence was checked')
    C.emit_formulas(d, heading=lambda k, F: '6.5.%d Row %d, %s' % (k + 1, F['fix'], F['doc']), level=3)

    # ------------------------------------------------------------------------------------------------
    d.h1('7. Files')
    d.p('**SHA-256 of the files** (at the time this record was generated):')
    files = [C.NAME + '.xlsx', 'tools/status_2026-10-28.json', 'tools/make_status_xlsx.py', 'tools/doc_status_common.py', 'tools/doc_status.py',
             'tools/doc_status_symbols.py', 'tools/doc_status_provenance.py', 'tools/make_docs.py', 'tools/docgen.py', 'tools/doc_common.py']
    d.code('\n'.join('%-30s %s' % (f, C.sha256(os.path.join(C.ROOT, f)) if os.path.exists(os.path.join(C.ROOT, f)) else 'missing') for f in files),
           'text')
    d.p('The first version of the spreadsheet, which is not in the repository, had the SHA-256 `%s`.' % FIRST_VERSION_SHA)
    return C.typographic(d)
