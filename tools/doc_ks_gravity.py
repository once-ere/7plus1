def compare(D):
    """(label, notebook values, Python values) for every number printed by both programs"""
    nm = D['nums']['ks']; ref = D['ref'].get('ks', ('', '', {}))[2]
    out = []
    flat_nb = [mnum(nm.get(k, '') or '') for k in ('m*', 'rho', 'eps')]
    flat_py = nums_in(ref.get(KEYS_PY['flat'], ''))[:3]
    out.append(('flat limit: $m^*$, $\\rho$, $\\varepsilon$', flat_nb, flat_py))
    for key, lab in (('prim', 'primordial $m^*(x_0)$'), ('papb', 'primordial $p_a/p_b$'), ('mod', 'modern $m^*(a)$'),
                     ('pbe', 'modern $p_b/\\varepsilon$ at $a=100$'), ('fut', 'far future $m^*(x_0)$'),
                     ('runE', 'Einstein run: $H_b(0)$; $a,b,H_a,H_b$ at $x_0=20$'),
                     ('runL', 'Einstein–Lovelock run: $H_b(0)$; $a,b,H_a,H_b$ at $x_0=20$')):
        a = nums_in(nm.get(KEYS_NB[key], ''))
        b = nums_in(ref.get(KEYS_PY[key], ''))
        if key in ('runE', 'runL'):
            a, b = a[:5], b[:5]          # the last number (the violation) is a residual, not a result
        out.append((lab, a, b))
    return out


def max_rel(a, b):
    if not a or not b or len(a) != len(b) or any(x is None for x in list(a) + list(b)):
        return None
    return max(abs(x - y)/max(abs(x), abs(y), 1e-300) for x, y in zip(a, b))


