def _q(x):
    """a Fraction as LaTeX"""
    from fractions import Fraction
    x = Fraction(x)
    return str(x.numerator) if x.denominator == 1 else r'\tfrac{%d}{%d}' % (x.numerator, x.denominator)


def _matrix_rows(v):
    """rows of a Mathematica matrix of integers printed as {{..},{..}}"""
    import re
    v = (v or '').strip()
    if not v.startswith('{{'):
        return None
    rows = re.findall(r'\{([^{}]*)\}', v)
    return [[x.strip().replace(' ', '') for x in r.split(',')] for r in rows]
