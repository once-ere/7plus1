def verify_lines(runs):
    """the lines of the output of tools/verify_7p1_nb.py that concern sections 25 and 26"""
    for title, out, *rest in (runs or []):
        if 'verify_7p1_nb' in title:
            return [l.rstrip() for l in out.split('\n') if l.startswith(('stage 6', 'stage 7')) or 'section 25' in l or 'section 26' in l
                    or l.startswith('VERDICT')]
    return []


def backup_text(rel):
    p = os.path.join(ROOT, rel)
    return ('%d bytes, SHA-256 `%s`' % (os.path.getsize(p), sha256(p))) if os.path.exists(p) else 'not present in this checkout'


